import re
import os
from pathlib import Path
from datetime import datetime

from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.lib.colors import HexColor
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib import colors


REDACTED_RE = re.compile(r'(\[[A-Z_ #]+(?:REDACTED|INFO REDACTED)\])')

_DARK = HexColor('#111827')
_MUTED = HexColor('#6b7280')
_RED = HexColor('#dc2626')
_RED_BG = HexColor('#fef2f2')
_BORDER = HexColor('#e5e7eb')
_ACCENT = HexColor('#4f46e5')


def generate_redacted_pdf(
    redacted_text: str,
    output_path: str,
    original_filename: str,
    pii_count: int = 0,
    summary: dict = None,
) -> str:
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        topMargin=0.8 * inch,
        bottomMargin=0.8 * inch,
        leftMargin=1.0 * inch,
        rightMargin=1.0 * inch,
        title=f"Redacted — {original_filename}",
        author="Personal Info Scrubber",
    )

    styles = getSampleStyleSheet()

    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontSize=9.5,
        leading=14,
        textColor=_DARK,
        fontName="Helvetica",
        wordWrap="LTR",
        spaceAfter=0,
    )

    story = []

    # ---- Header block ----
    story.append(_header_table(original_filename, pii_count, summary))
    story.append(Spacer(1, 0.18 * inch))
    story.append(HRFlowable(width="100%", thickness=1, color=_BORDER, spaceAfter=10))

    # ---- Body ----
    lines = redacted_text.split("\n")
    for line in lines:
        if not line.strip():
            story.append(Spacer(1, 4))
            continue
        xml = _line_to_xml(line)
        try:
            story.append(Paragraph(xml, body_style))
        except Exception:
            # Fall back to escaped plain text if XML parsing fails
            story.append(Paragraph(_escape(line), body_style))

    story.append(Spacer(1, 0.3 * inch))
    story.append(HRFlowable(width="100%", thickness=0.5, color=_BORDER))
    story.append(Spacer(1, 6))

    footer_style = ParagraphStyle(
        "Footer",
        parent=styles["Normal"],
        fontSize=7.5,
        textColor=_MUTED,
        fontName="Helvetica",
    )
    story.append(Paragraph(
        f"Generated by Personal Info Scrubber &bull; {datetime.now().strftime('%B %d, %Y %H:%M')}",
        footer_style,
    ))

    doc.build(story, onFirstPage=_add_watermark, onLaterPages=_add_watermark)
    return output_path


def _header_table(filename: str, pii_count: int, summary: dict) -> Table:
    summary = summary or {}
    pii_label = f"{pii_count} PII item{'s' if pii_count != 1 else ''} redacted"
    cats = ", ".join(f"{k} ({v})" for k, v in sorted(summary.items(), key=lambda x: -x[1])[:6])

    h1 = Paragraph(
        f'<font color="#dc2626"><b>REDACTED DOCUMENT</b></font>',
        ParagraphStyle("H1", fontSize=13, fontName="Helvetica-Bold", textColor=_RED, leading=16),
    )
    h2 = Paragraph(
        f'<font color="#374151">{_escape(filename)}</font>',
        ParagraphStyle("H2", fontSize=10, fontName="Helvetica", textColor=HexColor("#374151"), leading=13),
    )
    h3 = Paragraph(
        f'<font color="#6b7280">{pii_label}{(" — " + cats) if cats else ""}</font>',
        ParagraphStyle("H3", fontSize=8.5, fontName="Helvetica", textColor=_MUTED, leading=12),
    )

    t = Table([[h1], [h2], [h3]], colWidths=["100%"])
    t.setStyle(TableStyle([
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]))
    return t


def _line_to_xml(line: str) -> str:
    parts = REDACTED_RE.split(line)
    out = []
    for part in parts:
        if REDACTED_RE.fullmatch(part):
            out.append(f'<font color="#dc2626" name="Helvetica-Bold"><b>{_escape(part)}</b></font>')
        else:
            out.append(_escape(part))
    return "".join(out)


def _escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _add_watermark(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(_MUTED)
    canvas.drawRightString(
        doc.pagesize[0] - doc.rightMargin,
        doc.bottomMargin / 2,
        f"Page {canvas.getPageNumber()} — REDACTED",
    )
    canvas.restoreState()
